package lesson02;

public class C02Q01 {
    public static void main(String[] args) {
        int x = 100;
        int y = 200;
        System.out.println("x = " + x);
        System.out.println("y = " + y);
        int z = x + y;
        System.out.println("x + y = " + z);
        System.out.println("x + y = " + x + y);
        System.out.println("x + y = " + (x + y));
        System.out.println("x + y = " + x * y + x);
        
    }
}
